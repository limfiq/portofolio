-- ============================================================
-- 10. BLOGS
-- ============================================================
CREATE TYPE blog_status AS ENUM ('draft', 'published');

CREATE TABLE public.blogs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    slug VARCHAR(255) UNIQUE NOT NULL,
    content TEXT NOT NULL,
    tags VARCHAR(255),
    cover_image VARCHAR(255),
    status blog_status DEFAULT 'draft',
    views INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.blogs ENABLE ROW LEVEL SECURITY;

-- Trigger function untuk memperbarui kolom `updated_at`
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger yang akan dijalankan sebelum UPDATE pada tabel `blogs`
CREATE TRIGGER on_blogs_update
  BEFORE UPDATE ON public.blogs
  FOR EACH ROW
  EXECUTE PROCEDURE public.handle_updated_at();

-- ============================================================
-- 11. BLOG COMMENTS
-- ============================================================
CREATE TABLE public.blog_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blog_id BIGINT NOT NULL REFERENCES public.blogs (id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100),
    comment TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.blog_comments ENABLE ROW LEVEL SECURITY;

