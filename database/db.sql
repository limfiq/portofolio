-- ============================================================
-- Skrip ini disesuaikan untuk Supabase (PostgreSQL)
-- Tujuan: Menyimpan seluruh aktivitas dan publikasi dosen/peneliti
-- ============================================================

-- ============================================================
-- 1. USERS
-- Catatan: Supabase sudah memiliki tabel `auth.users`.
-- Sebaiknya buat tabel `profiles` yang terhubung ke `auth.users`.
-- Namun, untuk mengikuti struktur asli, tabel `users` dibuat sebagai tabel publik biasa.
-- Pertimbangkan untuk mengintegrasikannya dengan Supabase Auth di masa mendatang.
-- ============================================================
CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL, -- Di Supabase, password dikelola oleh Auth, jangan simpan di sini.
    photo VARCHAR(255),
    title VARCHAR(100),
    institution VARCHAR(150),
    biography TEXT,
    social_links JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
-- Aktifkan Row Level Security
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- Kebijakan: Izinkan semua orang untuk membaca data profil
CREATE POLICY "Allow public read access to profiles" ON public.users FOR
SELECT USING (true);

-- ============================================================
-- 2. EDUCATIONS
-- ============================================================
CREATE TABLE public.educations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    degree VARCHAR(100),
    major VARCHAR(150),
    institution VARCHAR(150),
    start_year INT,
    end_year INT,
    thesis_title VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.educations ENABLE ROW LEVEL SECURITY;

-- Kebijakan: Izinkan semua orang untuk membaca data pendidikan
CREATE POLICY "Allow public read access to educations" ON public.educations FOR
SELECT USING (true);

